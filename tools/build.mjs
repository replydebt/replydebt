// Bundles ES modules into ONE universal lazy-evaluated classic script (assets/app.bundle.js)
// that runs as the main UI on Window (http/https and file://) and as the Web Worker entry in WorkerGlobalScope.
// Also verifies/syncs Content-Security-Policy meta tags across index.html, privacy.html, and 404.html.
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';
import { buildCsp, buildNoscriptPixelHtml, buildPrivacyAnalyticsHtml } from '../assets/js/config.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const ENTRIES = ['assets/js/main.js', 'assets/js/worker/analyze.worker.js'];
const OUT = 'assets/app.bundle.js';

const rel = (abs) => path.relative(root, abs).split(path.sep).join('/');
const resolve = (fromRel, spec) => rel(path.resolve(root, path.dirname(fromRel), spec));

const modules = new Map();
const order = [];
const visiting = new Set();

function transform(file, code) {
  const deps = [];
  const exportPairs = []; // [exportedName, localName]

  // Multi-line or single-line named imports: import { a, b as c } from './x.js';
  code = code.replace(/^import\s*\{([\s\S]*?)\}\s*from\s*['"](\.[^'"]+)['"];?[ \t]*$/gm, (_, names, spec) => {
    const dep = resolve(file, spec);
    deps.push(dep);
    const binds = names
      .split(',')
      .map((s) => s.trim())
      .filter(Boolean)
      .map((s) => s.replace(/\s+as\s+/, ': '));
    return `const { ${binds.join(', ')} } = __req(${JSON.stringify(dep)});`;
  });
  if (/^import\s/m.test(code)) throw new Error(`${file}: unsupported import form`);

  // Dynamic import('./x.js') -> Promise.resolve(__req("..."))
  code = code.replace(/\bimport\(\s*['"](\.[^'"]+)['"]\s*\)/g, (_, spec) => {
    const dep = resolve(file, spec);
    deps.push(dep);
    return `Promise.resolve(__req(${JSON.stringify(dep)}))`;
  });

  // export function / async function / const / let / class
  code = code.replace(/^export\s+(async\s+function\*?|function\*?|const|let|class)\s+([A-Za-z_$][\w$]*)/gm, (_, kind, name) => {
    exportPairs.push([name, name]);
    return `${kind} ${name}`;
  });

  // export { a, b as c };
  code = code.replace(/^export\s*\{([\s\S]*?)\};?[ \t]*$/gm, (_, names) => {
    for (const part of names.split(',').map((s) => s.trim()).filter(Boolean)) {
      const m = part.match(/^([A-Za-z_$][\w$]*)(?:\s+as\s+([A-Za-z_$][\w$]*))?$/);
      if (!m) throw new Error(`${file}: unsupported export binding "${part}"`);
      exportPairs.push([m[2] || m[1], m[1]]);
    }
    return '';
  });

  if (/^export\s/m.test(code)) throw new Error(`${file}: unsupported export form`);
  if (/import\.meta/.test(code)) throw new Error(`${file}: import.meta is not allowed in the bundle`);

  return { deps, code, exportPairs };
}

function visit(file) {
  if (modules.has(file)) return;
  if (visiting.has(file)) throw new Error(`Circular import: ${file}`);
  visiting.add(file);
  const src = fs.readFileSync(path.join(root, file), 'utf8');
  const { deps, code, exportPairs } = transform(file, src);
  deps.forEach(visit);
  visiting.delete(file);
  const assignExports = exportPairs.map(([pub, loc]) => `__exp.${pub} = ${loc};`).join(' ');
  modules.set(
    file,
    `__defs[${JSON.stringify(file)}] = function (__exp, __req) {\n'use strict';\n${code}\n${assignExports ? `${assignExports}\n` : ''}};`,
  );
  order.push(file);
}

for (const entry of ENTRIES) visit(entry);

const banner = `/* Network Audit: generated by tools/build.mjs from assets/js (${order.length} modules). Do not edit directly. */`;
const bundle = `${banner}
(function () {
'use strict';
const __defs = Object.create(null);
const __cache = Object.create(null);
function __req(id) {
  if (__cache[id]) return __cache[id];
  const fn = __defs[id];
  if (!fn) throw new Error('Missing module: ' + id);
  const exp = Object.create(null);
  __cache[id] = exp;
  fn(exp, __req);
  return exp;
}

${order.map((f) => modules.get(f)).join('\n\n')}

if (typeof WorkerGlobalScope !== 'undefined' && self instanceof WorkerGlobalScope) {
  __req("assets/js/worker/analyze.worker.js");
} else {
  __req("assets/js/main.js");
}
})();
`;

// Verify classic-script syntax validity immediately via V8 parser.
new vm.Script(bundle, { filename: OUT });

const HTML_TARGETS = [
  { file: 'index.html', csp: buildCsp({ worker: true }), noscriptPixel: true },
  { file: 'privacy.html', csp: buildCsp({ worker: false }), privacyDisclosure: true },
  { file: '404.html', csp: buildCsp({ worker: false }) },
];

const CSP_RE = /(<meta\s+http-equiv="Content-Security-Policy"\s+content=")([^"]*)(")/i;
const PRIVACY_ANALYTICS_RE = /<li id="visit-analytics-disclosure">[\s\S]*?<\/li>/i;
const NOSCRIPT_RE = /(<noscript>\s*<p class="noscript-msg">[\s\S]*?<\/p>)(\s*<img\b[^>]*>)?(\s*<\/noscript>)/i;

export function syncHtmlContent(html, { file, csp, noscriptPixel = false, privacyDisclosure = false }, {
  pixelHtml = buildNoscriptPixelHtml(),
  disclosureHtml = buildPrivacyAnalyticsHtml(),
} = {}) {
  if (!CSP_RE.test(html)) throw new Error(`${file} is missing Content-Security-Policy meta tag.`);
  let out = html.replace(CSP_RE, `$1${csp}$3`);
  if (noscriptPixel) {
    if (!NOSCRIPT_RE.test(out)) throw new Error(`${file} is missing <noscript> block.`);
    out = out.replace(NOSCRIPT_RE, (_, head, _oldImg, tail) => `${head}${pixelHtml ? `\n    ${pixelHtml}` : ''}${tail}`);
  }
  if (privacyDisclosure) {
    if (!PRIVACY_ANALYTICS_RE.test(out)) throw new Error(`${file} is missing #visit-analytics-disclosure element.`);
    out = out.replace(PRIVACY_ANALYTICS_RE, disclosureHtml);
  }
  return out;
}

const isCli = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isCli) {
  const isCheck = process.argv.includes('--check');

  if (isCheck) {
    const current = fs.existsSync(path.join(root, OUT)) ? fs.readFileSync(path.join(root, OUT), 'utf8') : '';
    if (current !== bundle) {
      console.error(`${OUT} is out of date. Run: node tools/build.mjs`);
      process.exit(1);
    }
    for (const target of HTML_TARGETS) {
      const htmlPath = path.join(root, target.file);
      if (!fs.existsSync(htmlPath)) {
        console.error(`Missing HTML file: ${target.file}`);
        process.exit(1);
      }
      const html = fs.readFileSync(htmlPath, 'utf8');
      const expected = syncHtmlContent(html, target);
      if (html !== expected) {
        console.error(`${target.file} is out of sync with assets/js/config.js. Run: node tools/build.mjs`);
        process.exit(1);
      }
    }
    console.log(`${OUT}, HTML CSP headers, and privacy disclosures are up to date (${order.length} modules).`);
    process.exit(0);
  }

  fs.writeFileSync(path.join(root, OUT), bundle);
  for (const target of HTML_TARGETS) {
    const htmlPath = path.join(root, target.file);
    if (!fs.existsSync(htmlPath)) continue;
    const html = fs.readFileSync(htmlPath, 'utf8');
    const updated = syncHtmlContent(html, target);
    if (updated !== html) fs.writeFileSync(htmlPath, updated);
  }
  console.log(`Built ${OUT}: ${order.length} modules, ${(bundle.length / 1024).toFixed(1)} KB`);
}
